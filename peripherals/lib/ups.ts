// Pure helpers for the UPS driver: which USB devices are UPSes (reusing NUT's own udev
// table), NUT config generation, `upsc` parsing and status-flag decoding. No I/O, so the
// whole lot is unit-tested with fixtures.

// ---------- Which USB devices are UPSes ----------

export interface UpsId {
  vid: string;
  pid: string; // "*" = any product from this vendor
  driver: string; // NUT driver binary in /lib/nut
  models: string; // NUT's comment, e.g. "CP1200AVR/BC1200D, …"
}

/**
 * NUT ships a generated udev file listing every USB ID it supports, each preceded by a
 * comment naming the models and the driver: `#  900AVR/BC900D  - usbhid-ups`. Parsing it
 * means DeskyPi recognises exactly what the installed NUT can drive, and picks the right
 * driver (nutdrv_qx, tripplite_usb, … not just usbhid-ups).
 */
export function parseNutUdevRules(text: string): UpsId[] {
  const out: UpsId[] = [];
  let comment = "";
  for (const line of text.split("\n")) {
    const c = /^#\s+(.*?)\s+-\s+([a-z0-9_-]+)\s*$/.exec(line);
    if (c) {
      comment = line;
      continue;
    }
    const m = /ATTR\{idVendor\}=="([0-9a-fA-F]{4})", ATTR\{idProduct\}=="([0-9a-fA-F]{4})"/.exec(line);
    if (m) {
      const cm = /^#\s+(.*?)\s+-\s+([a-z0-9_-]+)\s*$/.exec(comment);
      out.push({ vid: m[1].toLowerCase(), pid: m[2].toLowerCase(), driver: cm?.[2] || "usbhid-ups", models: cm?.[1] || "" });
      comment = "";
    }
  }
  return out;
}

/** Used when NUT's rules file is missing, plus whole-vendor matches the rules can't express. */
export const BUILTIN_IDS: UpsId[] = [
  { vid: "051d", pid: "0002", driver: "usbhid-ups", models: "APC" },
  { vid: "051d", pid: "0003", driver: "usbhid-ups", models: "APC (modern)" },
  { vid: "0764", pid: "0501", driver: "usbhid-ups", models: "CyberPower" },
  { vid: "0764", pid: "0601", driver: "usbhid-ups", models: "CyberPower" },
  { vid: "0463", pid: "ffff", driver: "usbhid-ups", models: "Eaton / MGE" },
  { vid: "0463", pid: "0001", driver: "usbhid-ups", models: "Eaton / MGE" },
  { vid: "09ae", pid: "*", driver: "usbhid-ups", models: "Tripp Lite" },
  { vid: "10af", pid: "*", driver: "usbhid-ups", models: "Liebert" },
];

/** Exact NUT match first, then the vendor-wide fallbacks. */
export function matchUps(vid: string, pid: string, table: UpsId[]): UpsId | null {
  vid = (vid || "").toLowerCase();
  pid = (pid || "").toLowerCase();
  return table.find((t) => t.vid === vid && t.pid === pid) || BUILTIN_IDS.find((t) => t.vid === vid && (t.pid === pid || t.pid === "*")) || null;
}

/**
 * HID Power Device class: a HID report descriptor that opens the Power Device (0x84) or
 * Battery System (0x85) usage page. That's how a UPS from a vendor nobody has listed still
 * gets recognised: usbhid-ups speaks the class generically.
 * Usage Page items: 0x05 <1 byte> or 0x06 <2 bytes little-endian>.
 */
export function isPowerDeviceDescriptor(desc: Uint8Array): boolean {
  for (let i = 0; i < desc.length; ) {
    const b = desc[i];
    if (b === 0xfe) {
      // long item: skip
      i += 3 + (desc[i + 1] || 0);
      continue;
    }
    const size = [0, 1, 2, 4][b & 3];
    if ((b & 0xfc) === 0x04) {
      const page = size === 1 ? desc[i + 1] : size === 2 ? desc[i + 1] | (desc[i + 2] << 8) : -1;
      if (page === 0x84 || page === 0x85) return true;
    }
    i += 1 + size;
  }
  return false;
}

// ---------- NUT config ----------

export interface UpsSection {
  name: string; // NUT ups name, e.g. "deskypi"
  driver: string;
  port: string; // "auto" for USB, the .dev path for dummy-ups
  vid?: string;
  pid?: string;
  serial?: string;
  bus?: string;
  desc?: string;
}

const q = (s: string) => `"${s.replace(/["\\]/g, "\\$&")}"`;

export function upsConf(sections: UpsSection[]): string {
  let out = "# Generated by DeskyPi; private to its NUT children. Not /etc/nut.\nmaxretry = 3\n";
  for (const s of sections) {
    out += `\n[${s.name}]\n  driver = ${s.driver}\n  port = ${q(s.port)}\n`;
    if (s.vid) out += `  vendorid = ${s.vid}\n`;
    if (s.pid) out += `  productid = ${s.pid}\n`;
    // Two identical UPSes are told apart by serial; failing that, by USB bus.
    if (s.serial) out += `  serial = ${q(s.serial)}\n`;
    else if (s.bus) out += `  bus = ${q(s.bus)}\n`;
    if (s.desc) out += `  desc = ${q(s.desc)}\n`;
  }
  return out;
}

export function upsdConf(port: number, shared: boolean): string {
  return `# Generated by DeskyPi\nLISTEN ${shared ? "0.0.0.0" : "127.0.0.1"} ${port}\nMAXAGE 25\n`;
}

/** A read-only monitoring account, so `upsmon` on other machines can follow this UPS when shared. */
export function upsdUsers(user: string, password: string): string {
  return `# Generated by DeskyPi\n[${user}]\n  password = ${password}\n  upsmon secondary\n`;
}

// ---------- upsc ----------

export function parseUpsc(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const i = line.indexOf(": ");
    if (i > 0 && /^[a-z0-9_.]+$/i.test(line.slice(0, i))) out[line.slice(0, i)] = line.slice(i + 2).trim();
  }
  return out;
}

export const STATUS_WORDS: Record<string, string> = {
  OL: "On mains",
  OB: "On battery",
  LB: "Low battery",
  HB: "High battery",
  RB: "Replace battery",
  CHRG: "Charging",
  DISCHRG: "Discharging",
  BYPASS: "On bypass",
  CAL: "Calibrating",
  OFF: "Output off",
  OVER: "Overloaded",
  TRIM: "Trimming high voltage",
  BOOST: "Boosting low voltage",
  FSD: "Forced shutdown",
  ALARM: "Alarm",
  TEST: "Self-test",
  ECO: "Eco mode",
};

export function decodeStatus(s: string): { flag: string; word: string; severity: "ok" | "warn" | "bad" | "info" }[] {
  const sev: Record<string, "ok" | "warn" | "bad" | "info"> = { OL: "ok", OB: "warn", LB: "bad", RB: "warn", OVER: "bad", FSD: "bad", ALARM: "bad", BYPASS: "warn", OFF: "bad" };
  return (s || "").split(/\s+/).filter(Boolean).map((flag) => ({ flag, word: STATUS_WORDS[flag] || flag, severity: sev[flag] || "info" }));
}

/** Power events worth a line in the timeline when the status flags change. */
export function statusEvents(prev: string, next: string): string[] {
  const a = new Set((prev || "").split(/\s+/).filter(Boolean));
  const b = new Set((next || "").split(/\s+/).filter(Boolean));
  const rose = (f: string) => b.has(f) && !a.has(f);
  const fell = (f: string) => a.has(f) && !b.has(f);
  const out: string[] = [];
  if (rose("OB")) out.push("Power lost: running on battery");
  if (rose("OL") && a.has("OB")) out.push("Power restored: back on mains");
  if (rose("LB")) out.push("Battery low");
  if (fell("LB")) out.push("Battery no longer low");
  if (rose("RB")) out.push("UPS says: replace battery");
  if (rose("OVER")) out.push("UPS overloaded");
  if (fell("OVER")) out.push("Overload cleared");
  if (rose("BYPASS")) out.push("UPS on bypass (load not protected)");
  if (rose("FSD")) out.push("UPS forced shutdown in progress");
  if (rose("OFF")) out.push("UPS output off");
  return out;
}

/** "battery.runtime" seconds → "1 h 23 min" / "12 min" / "45 s". */
export function fmtRuntime(sec: number): string {
  if (!Number.isFinite(sec)) return "";
  if (sec < 60) return `${Math.round(sec)} s`;
  const m = Math.round(sec / 60);
  return m < 60 ? `${m} min` : `${Math.floor(m / 60)} h ${m % 60} min`;
}
